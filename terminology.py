def classify_category(text: str) -> str:
    """Грубая классификация свободного текста в один из бакетов. 'other', если ничего не подошло."""
    t = (text or "").lower()
    for key, words in _KEYWORDS.items():
        if any(w in t for w in words):
            return key
    return "other"


def terms_for(category_key: str | None) -> dict[str, str]:
    return _TERMS.get(category_key or "other", _TERMS["other"])
